// scripts/build-sql-test.mjs
// `supabase db query --linked` runs through the Management API, which has no psql \ir — so a rolled-back migration
// test is one file with the migrations pasted in. This writes scripts/test-<n>.sql from its head, the migrations it
// needs, and its body:  node scripts/build-sql-test.mjs 0025
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const n = process.argv[2]
const needs = { '0025': ['0024', '0025'] }[n] ?? [n]
const dir = new URL('../supabase/migrations/', import.meta.url)
const files = readdirSync(dir)
const migration = (m) => readFileSync(new URL(files.find((f) => f.startsWith(`${m}_`)), dir), 'utf8')
const part = (p) => readFileSync(new URL(`test-${n}.${p}.sql`, import.meta.url), 'utf8')

writeFileSync(
  new URL(`test-${n}.sql`, import.meta.url),
  `${part('head')}\n-- Generated by scripts/build-sql-test.mjs from test-${n}.head.sql, ${needs.join(' + ')}, test-${n}.body.sql.\nbegin;\n${needs.map(migration).join('\n')}\n${part('body')}`
)
